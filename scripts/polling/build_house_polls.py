"""Write the House district polling table the polls whiteboard shows.
Reads the POLLS table in the forecast model's house_mode.py, the district polling averages the House forecast uses,
and joins each district to the published forecast in public/forecast/model.json.
usage: python3 -I scripts/polling/build_house_polls.py /tmp/site /tmp/fcrun/TPSI_B/model/FLH/house_mode.py"""
import ast, json, re, sys, datetime
SITE, SRC = sys.argv[1], sys.argv[2]
src = open(SRC).read()
i = src.index("\nPOLLS = {")
j = src.index("\nUNCONTESTED", i)
node = ast.parse(src[i:j].strip()).body[0].value
def val(n):
    if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "dict": return {k.arg: ast.literal_eval(k.value) for k in n.keywords}
    return ast.literal_eval(n)
polls = {}
for k, v in zip(node.keys, node.values):
    key = ast.literal_eval(k)
    polls[key] = {ast.literal_eval(dk): val(dv) for dk, dv in zip(v.keys, v.values)}
model = json.load(open(f"{SITE}/public/forecast/model.json"))
house = {(r["st"], int(r["district"] or 1)): r for r in model["races"] if r["office"] == "house"}
rows = []
for key, dd in polls.items():
    st = key[:2]
    for d, x in dd.items():
        r = house.get((st, int(d))) or house.get((st, 1) if int(d) == 1 else (st, -1))
        if not r: continue
        dm = round(float(x["d"]) - float(x["r"]), 1)
        rows.append({"st": st, "d": int(d), "id": r["id"], "name": r["name"], "dem": r.get("dem"), "gop": r.get("gop"), "pd": x["d"], "pr": x["r"], "poll": dm,
                     "fm": round(-r["est"]["margin"], 1), "fp": round(1 - r["est"]["prob"], 3), "href": f"/forecast/{st.lower()}/house-{int(d)}"})
rows.sort(key=lambda r: (abs(r["poll"]), r["st"], r["d"]))
out = f"""// GENERATED by scripts/polling/build_house_polls.py on {datetime.date.today().isoformat()}. Do not hand edit.
// District polling averages the House forecast uses: each district's polls averaged evenly, campaign and party
// internals moved 1.5 points against their own side first. poll = D minus R; fm = forecast D margin; fp = D win chance.
export type HouseDistrictPoll = {{ st: string; d: number; id: string; name: string; dem: string | null; gop: string | null; pd: number; pr: number; poll: number; fm: number; fp: number; href: string }};
export const HOUSE_DISTRICT_POLLS: HouseDistrictPoll[] = {json.dumps(rows, separators=(",", ":"))};
"""
open(f"{SITE}/app/_polling/lib/houseDistrictPolls.ts", "w").write(out)
print(len(rows), "districts")
